//! Prepare deployment without compiling or copying library content locally.
use crate::{Library, atomic_write};
use anyhow::{Context, Result, ensure};
use serde::Serialize;
use std::{fs, path::PathBuf};

const COMPOSE: &str = include_str!("../../../web-server/docker-compose.yml");
const HEADER: &str = "# Generated by dox: web deployment v1\n";

#[derive(Serialize)]
pub struct WebDeploymentReport {
    pub destination: PathBuf,
}

impl Library {
    pub fn prepare_web_deployment(&self) -> Result<WebDeploymentReport> {
        let name = self
            .root()
            .file_name()
            .unwrap_or_default()
            .to_string_lossy();
        let name = if name.is_empty() { "Notes" } else { &name };
        // JSON strings are valid YAML scalars. Escape Compose interpolation as
        // well, so library names containing dollars remain literal.
        let name = serde_json::to_string(&name.replace('$', "$$"))?;
        let compose = COMPOSE.replace("__DOX_LIBRARY_NAME__", &name);
        let directory = self.root().join("web");
        match fs::symlink_metadata(&directory) {
            Ok(metadata) => ensure!(
                metadata.file_type().is_dir(),
                "web must be a real directory, not a file or symlink"
            ),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                fs::create_dir(&directory).context("Could not create web directory")?;
            }
            Err(error) => return Err(error.into()),
        }
        let destination = directory.join("docker-compose.yml");
        match fs::symlink_metadata(&destination) {
            Ok(metadata) => {
                ensure!(
                    metadata.file_type().is_file(),
                    "Compose destination must be a regular file"
                );
                let previous = fs::read_to_string(&destination)?;
                ensure!(
                    previous.starts_with(HEADER),
                    "Refusing to overwrite a Compose file not generated by dox"
                );
                if previous != compose {
                    atomic_write(&destination, compose.as_bytes())?;
                }
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                // Do not overwrite a file that appeared after the existence check.
                use std::io::Write;
                let mut temporary = tempfile::NamedTempFile::new_in(&directory)?;
                temporary.write_all(compose.as_bytes())?;
                temporary.as_file().sync_all()?;
                temporary
                    .persist_noclobber(&destination)
                    .map_err(|error| error.error)?;
            }
            Err(error) => return Err(error.into()),
        }
        Ok(WebDeploymentReport { destination })
    }
}
