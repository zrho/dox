use regex::Regex;
use serde::{Deserialize, Serialize};
use serde_json::Value;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Severity {
    Error,
    Warning,
    Proposal,
}

/// A description of a future suggested action, never an instruction to execute it.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DiagnosticAction {
    pub kind: String,
    pub title: String,
    pub payload: Value,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Diagnostic {
    pub id: String,
    pub severity: Severity,
    pub code: String,
    pub message: String,
    pub note_id: Option<String>,
    pub document: Option<String>,
    /// One-based source coordinates, when supplied by the compiler.
    pub line: Option<usize>,
    pub column: Option<usize>,
    pub target_note_id: Option<String>,
    #[serde(default)]
    pub actions: Vec<DiagnosticAction>,
}
impl Diagnostic {
    pub fn new(
        severity: Severity,
        code: &str,
        note_id: &str,
        document: Option<&str>,
        message: impl Into<String>,
    ) -> Self {
        let message = message.into();
        Self {
            id: crate::digest(
                format!("{severity:?}:{code}:{note_id}:{document:?}:{message}").as_bytes(),
            ),
            severity,
            code: code.into(),
            message,
            note_id: Some(note_id.into()),
            document: document.map(str::to_owned),
            line: None,
            column: None,
            target_note_id: None,
            actions: vec![],
        }
    }
}

pub(crate) fn compiler_diagnostics(
    stderr: &[u8],
    note_id: &str,
    document: &str,
) -> Vec<Diagnostic> {
    let text = String::from_utf8_lossy(stderr);
    let mut blocks: Vec<(Severity, String)> = vec![];
    for line in text.lines() {
        let severity = if line.starts_with("error:") || line.contains(": error:") {
            Some(Severity::Error)
        } else if line.starts_with("warning:") || line.contains(": warning:") {
            Some(Severity::Warning)
        } else {
            None
        };
        if let Some(severity) = severity {
            blocks.push((severity, line.into()));
        } else if let Some((_, message)) = blocks.last_mut() {
            message.push('\n');
            message.push_str(line);
        }
    }
    let location = Regex::new(r"^(.+?):(\d+):(\d+):").expect("valid location pattern");
    blocks
        .into_iter()
        .filter_map(|(severity, message)| {
            // These are generated by our compiler invocation, not by note content.
            if severity == Severity::Warning
                && (message.contains("html export is under active development")
                    || message.contains("subcommand is deprecated"))
            {
                return None;
            }
            let mut diagnostic = Diagnostic::new(
                severity,
                if severity == Severity::Error {
                    "typst-compile"
                } else {
                    "typst-warning"
                },
                note_id,
                Some(document),
                message.trim(),
            );
            if let Some(capture) = location.captures(&message) {
                diagnostic.document = Some(capture[1].to_owned());
                diagnostic.line = capture[2].parse().ok();
                diagnostic.column = capture[3].parse().ok();
            }
            Some(diagnostic)
        })
        .collect()
}
